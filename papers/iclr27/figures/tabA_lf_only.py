#!/usr/bin/env python3
"""Appendix table (rebuttal item A) - pretrain-only (LF-only) baseline on CC labels.

Final ensembles of LF-only (DFT-trained members with per-element reference energies
refit to the CC training residuals, step ``lfonly_baseline``), HF-only and LF->HF on
the four test sets: RMSE (meV/atom) and TU Spearman / AUSE / ENCE, uncalibrated and
support-filtered. Five-split mean with 95% Student-t interval (df = 4); RMSE and ENCE
as geometric means (log-space interval), as computed by
``python -m uq.evaluation.compare_lf_only``. This script only reads
``results/tables/lf_only_vs_hf.csv`` (ledger 2026-11-07 "LF-only on CC labels") and
writes ``out/tabA_lf_only.tex`` (booktabs); values are rounded for display only.
"""

import csv

from common import OUT, ROOT, TESTS

TABLE = ROOT / "results" / "tables" / "lf_only_vs_hf.csv"
MODELS = (("lf_only", "LF-only (E$_0$ refit)"), ("hf_only", "HF-only"), ("lf_to_hf", "LF$\\to$HF"))
# (metric, uncertainty_type, header, scale, decimals)
COLUMNS = (("rmse", "ensemble", "RMSE (meV/atom) $\\downarrow$", 1000.0, 1),
           ("spearman", "total", "TU Spearman $\\uparrow$", 1.0, 3),
           ("ause", "total", "TU AUSE $\\downarrow$", 1.0, 3),
           ("ence", "total", "TU ENCE $\\downarrow$", 1.0, 2))


def load():
    out = {}
    with TABLE.open() as handle:
        for row in csv.DictReader(handle):
            if row["missing"]:
                raise RuntimeError(f"{TABLE.name}: missing splits for {row}")
            if int(row["n_splits"]) != 5:
                raise RuntimeError(f"{TABLE.name}: {row['n_splits']} splits for {row}")
            key = (row["dataset"].removeprefix("ani1x-"), row["test"], row["metric"], row["uncertainty_type"],
                   row["model"])
            out[key] = tuple(float(row[k]) for k in ("value_mean", "value_ci95_low", "value_ci95_high"))
    return out


def cell(values, scale, decimals):
    m, lo, hi = (scale * v for v in values)
    return f"{m:.{decimals}f} {{\\scriptsize [{lo:.{decimals}f}, {hi:.{decimals}f}]}}"


def main():
    data = load()
    lines = ["% Generated by papers/iclr27/figures/tabA_lf_only.py from results/tables/lf_only_vs_hf.csv",
             "\\begin{tabular}{ll" + "c" * len(COLUMNS) + "}", "\\toprule",
             "Test & Protocol & " + " & ".join(h for _, _, h, _, _ in COLUMNS) + " \\\\", "\\midrule"]
    for i, (kind, test, name) in enumerate(TESTS):
        if i:
            lines.append("\\addlinespace")
        for j, (model, label) in enumerate(MODELS):
            cells = [cell(data[(kind, test, m, u, model)], s, d) for m, u, _, s, d in COLUMNS]
            lines.append(f"{name if j == 0 else ''} & {label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "tabA_lf_only.tex"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
