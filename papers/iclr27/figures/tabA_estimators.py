#!/usr/bin/env python3
"""Appendix table (rebuttal item D) - uncertainty estimators: MSE ensemble vs MVE ensemble vs one MVE model.

For HF-only and LF->HF on the four test sets, the uncertainty signal of each estimator, M = 10 unless
"one model": EU of a plain MSE deep ensemble (its only signal), EU and TU of the MVE ensemble (the
paper's), and AU of a single MVE member (mean over the ten). Uncalibrated, per atom; five-split mean
with 95% Student-t interval (df = 4); ENCE as geometric mean (log-space interval), as computed by
``python -m uq.evaluation.compare_uq`` (ledger 2026-11-03/04 HF-only, 2026-11-08 LF->HF). This script
only reads ``results/tables/mse_vs_mve.csv`` and writes ``out/tabA_estimators_{spearman,ence}.tex`` (booktabs); a
(dataset, protocol, test) whose MSE ensemble is not evaluated on all five splits is printed as
"pending", never aggregated over fewer splits.
"""

import csv

from common import OUT, ROOT, TESTS

TABLE = ROOT / "results" / "tables" / "mse_vs_mve.csv"
PROTOCOLS = (("hf-only", "HF-only"), ("lf-to-hf", "LF$\\to$HF"))
SIGNALS = (("mse_eu", "MSE ens.\\ EU"), ("mve_eu", "MVE ens.\\ EU"), ("mve_tu", "MVE ens.\\ TU"),
           ("mve_single_au", "one MVE AU"))
METRICS = (("spearman", "Spearman", 3), ("ence", "ENCE", 2))


def load():
    out, missing = {}, set()
    with TABLE.open() as handle:
        for row in csv.DictReader(handle):
            key = (row["dataset"].removeprefix("ani1x-"), row["protocol"], row["test"])
            if row["missing"]:
                missing.add(key)
                continue
            if int(float(row["n_splits"])) != 5:
                raise RuntimeError(f"{TABLE.name}: {row['n_splits']} splits for {row}")
            out[key + (row["metric"], row["signal"])] = tuple(
                float(row[k]) for k in ("value_mean", "value_ci95_low", "value_ci95_high"))
    return out, missing


def cell(values, decimals):
    m, lo, hi = values
    return f"{m:.{decimals}f} {{\\scriptsize [{lo:.{decimals}f}, {hi:.{decimals}f}]}}"


def table(data, missing, metric, decimals):
    lines = ["\\begin{tabular}{ll" + "c" * len(SIGNALS) + "}", "\\toprule",
             "Test & Protocol & " + " & ".join(h for _, h in SIGNALS) + " \\\\", "\\midrule"]
    for i, (kind, test, name) in enumerate(TESTS):
        if i:
            lines.append("\\addlinespace")
        for j, (protocol, label) in enumerate(PROTOCOLS):
            if (kind, protocol, test) in missing:
                cells = ["pending"] * len(SIGNALS)
            else:
                cells = [cell(data[(kind, protocol, test, metric, s)], decimals) for s, _ in SIGNALS]
            lines.append(f"{name if j == 0 else ''} & {label} & " + " & ".join(cells) + " \\\\")
    return lines + ["\\bottomrule", "\\end{tabular}"]


def main():
    data, missing = load()
    OUT.mkdir(parents=True, exist_ok=True)
    for metric, _, decimals in METRICS:
        lines = [f"% Generated by papers/iclr27/figures/tabA_estimators.py from results/tables/mse_vs_mve.csv ({metric})"]
        lines += table(data, missing, metric, decimals)
        path = OUT / f"tabA_estimators_{metric}.tex"
        path.write_text("\n".join(lines) + "\n")
        print(f"wrote {path}" + (f" ({len(missing)} pending tests)" if missing else ""))


if __name__ == "__main__":
    main()
